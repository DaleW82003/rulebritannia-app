const BASE_SORT_ORDER = -1000;

export async function seedPredefinedGuides(pool) {
  const titles = PREDEFINED_GUIDES.map((guide) => guide.title);
  let inserted = 0;
  let updated = 0;

  await pool.query("BEGIN");
  try {
    const { rows } = await pool.query(
      "SELECT title FROM guides_items WHERE title = ANY($1)",
      [titles]
    );
    const existingTitles = new Set(rows.map((row) => row.title));

    for (const [index, guide] of PREDEFINED_GUIDES.entries()) {
      const sortOrder = BASE_SORT_ORDER + index;
      if (existingTitles.has(guide.title)) {
        const result = await pool.query(
          "UPDATE guides_items SET sort_order = $2 WHERE title = $1 AND sort_order <> $2",
          [guide.title, sortOrder]
        );
        updated += result.rowCount || 0;
        continue;
      }

      await pool.query(
        "INSERT INTO guides_items (title, body, sort_order) VALUES ($1, $2, $3)",
        [guide.title, guide.body, sortOrder]
      );
      inserted += 1;
    }

    await pool.query("COMMIT");
    return { inserted, updated };
  } catch (error) {
    await pool.query("ROLLBACK");
    throw error;
  }
}
